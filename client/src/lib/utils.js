// Utility functions
export function estimateReadTime(text) {
  if (!text) return '< 1 min';
  const words = text.trim().split(/\s+/).length;
  const mins = Math.ceil(words / 200);
  if (mins < 1) return '~30s read';
  return `~${mins} min read`;
}

export function copyToClipboard(text) {
  return navigator.clipboard.writeText(text);
}

export function exportAsMarkdown(query, results) {
  const sections = [
    `# ELI5 Cognitive Breakdown\n\n**Query:** ${query}\n\n---\n`,
    `## 🟡 Level 01 — 5-Year-Old (Pure Wonder)\n\n${results.eli5}\n\n---\n`,
    `## 🔵 Level 02 — Teenager (Kinetic Clarity)\n\n${results.teen}\n\n---\n`,
    `## 🟢 Level 03 — Adult / Expert (Executive Precision)\n\n${results.expert}\n\n---\n`,
    `*Generated by ELI5 Simplifier — Cognitive Engine v2.4*\n*${new Date().toLocaleString()}*`
  ];
  return sections.join('\n');
}

export function downloadMarkdown(content, filename = 'eli5-explanation.md') {
  const blob = new Blob([content], { type: 'text/markdown' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  a.click();
  URL.revokeObjectURL(url);
}

export function speakText(text, rate = 0.9, pitch = 1) {
  if (!window.speechSynthesis) return;
  window.speechSynthesis.cancel();
  const utterance = new SpeechSynthesisUtterance(text);
  utterance.rate = rate;
  utterance.pitch = pitch;
  // Strip markdown-ish formatting
  utterance.text = text.replace(/\*\*/g, '').replace(/\*/g, '').replace(/#{1,6}\s/g, '');
  window.speechSynthesis.speak(utterance);
}

export function stopSpeaking() {
  if (window.speechSynthesis) window.speechSynthesis.cancel();
}

export function formatTimeAgo(timestamp) {
  const diff = Date.now() - timestamp;
  const mins = Math.floor(diff / 60000);
  const hours = Math.floor(diff / 3600000);
  const days = Math.floor(diff / 86400000);
  if (mins < 1) return 'Just now';
  if (mins < 60) return `${mins}m ago`;
  if (hours < 24) return `${hours}h ago`;
  return `${days}d ago`;
}

// Simple markdown-to-JSX text renderer (bold, italic, line breaks)
export function renderMarkdown(text) {
  if (!text) return '';
  return text
    .replace(/\*\*(.*?)\*\*/g, '<strong>$1</strong>')
    .replace(/\*(.*?)\*/g, '<em>$1</em>')
    .replace(/`(.*?)`/g, '<code>$1</code>')
    .replace(/\n\n/g, '</p><p>')
    .replace(/\n/g, '<br/>');
}
